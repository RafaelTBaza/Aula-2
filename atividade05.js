//Escreva um programa que leia dois números e uma operação (adição, subtração, multiplicação, divisão) e realize a operação entre os dois números.


var num1 = 5
var num2 = 15
var op = "*"

if(op == "/"){
    console.log(num1 / num2)
}

if(op == "+"){
    console.log(num1 + num2)
}

if(op == "-"){
    console.log(num1 - num2)
}

if(op == "*"){
    console.log(num1 * num2)
}